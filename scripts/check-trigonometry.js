import assert from "node:assert/strict";
import { additionFormulaFacts, degreesToRadians, doubleAngleFacts, radiansToDegrees, rightTriangleTrig, transformedTrigValue, trigFunctionValue, trigRelations } from "../static/atlas/math/trigonometry.js";
assert.ok(Math.abs(rightTriangleTrig(30).sin - 0.5) < 1e-10);
assert.ok(Math.abs(rightTriangleTrig(60).cos - 0.5) < 1e-10);
assert.ok(Math.abs(rightTriangleTrig(45).tan - 1) < 1e-10);
assert.equal(rightTriangleTrig(90).tan, null);
[0, 30, 45, 60, 120, 180].forEach((theta) => assert.ok(Math.abs(trigRelations(theta).squareSum - 1) < 1e-10));
assert.ok(Math.abs(degreesToRadians(180) - Math.PI) < 1e-10);
assert.ok(Math.abs(radiansToDegrees(Math.PI / 2) - 90) < 1e-10);
assert.ok(Math.abs(trigFunctionValue({ functionName: "sin", x: Math.PI / 6 }) - 0.5) < 1e-10);
assert.equal(trigFunctionValue({ functionName: "tan", x: Math.PI / 2 }), null);
assert.equal(transformedTrigValue({ amplitude: 2, frequency: 1, phase: 0, verticalShift: 1, x: Math.PI / 2 }), 3);
const addition = additionFormulaFacts(Math.PI / 6, Math.PI / 6);
assert.ok(Math.abs(addition.sinSum - addition.sinExpanded) < 1e-10);
const double = doubleAngleFacts(Math.PI / 6);
assert.ok(Math.abs(double.cosDouble - double.cosFromSin) < 1e-10);
console.log("Trigonometry math: PASS (special values, conversions, transforms, addition and double-angle identities)");
